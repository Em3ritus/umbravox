uint8_t row(char ch, int r) {
    if (r < 0 || r >= H) return 0;
    unsigned c = (unsigned char)ch;
    if (c >= 'a' && c <= 'z') c -= 32;   // fold to caps
    if (c < 32 || c > 95) return 0;
    return GLYPHS[c - 32][r];
}

int width(const char* s, int scale) {
    if (!s || !*s) return 0;
    int n = 0;
    while (s[n]) n++;
    return (n * ADV - 1) * scale;   // drop the gap after the last glyph
}

