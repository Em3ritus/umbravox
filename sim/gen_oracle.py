#!/usr/bin/env python3
# Generate oracle_hits.inc from the delivered geometry.json: the complete set
# of expected hit rects for every SCAN/DOMAIN state at both sizes. The host test
# compares the engine's hits against this, so no case can be silently skipped.
#   python3 gen_oracle.py <geometry.json> > oracle_hits.inc
import json, sys

geom = sys.argv[1]
S = {s['name']: s for s in json.load(open(geom))['screens']}
states = ['active', 'acquiring', 'stale', 'off', 'threat']

print("// generated by gen_oracle.py from geometry.json -- do not edit")
print("struct ORect { int x, y, w, h; };")
print("struct OCase { const char* screen; const char* state; int W, H, n; ORect r[16]; };")
print("static const OCase ORACLE[] = {")
for scr in ['scan', 'domain']:
    for W in (480, 320):
        H = 320 if W == 480 else 240
        for st in states:
            nm = f'{scr}-{st}-{W}'
            if nm not in S:
                continue
            rects = [h['rect'] for h in S[nm]['hits']]
            rs = ", ".join("{%d,%d,%d,%d}" % (r[0], r[1], r[2], r[3]) for r in rects)
            print('  {"%s","%s",%d,%d,%d,{%s}},' % (scr, st, W, H, len(rects), rs))
print("};")
print("static const int ORACLE_N = (int)(sizeof(ORACLE)/sizeof(ORACLE[0]));")
