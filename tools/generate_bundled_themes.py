#!/usr/bin/env python3
"""Generate firmware rows and losslessly packed artwork from approved packs."""
import json
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
FOLDERS = ['slick', 'z-baph0mau5', 'z-em3ritus', 'z-ember', 'z-skuld']
ROLES = 'void panel grid edge edgeLit dim text bright witch witchHi bone sweep sweepHi live liveHi magenta ice green amber red'.split()
SWEEPS = 'radar gaze pulse star candle galaxy orbit starfall pulsar comet aurora'.split()
RITES = 'ward supernova vortex comet lockon'.split()
def rgb(s):
    n=int(s[1:],16); return ((n>>19)<<11)|(((n>>10)&63)<<5)|((n>>3)&31)
def hexes(a): return ','.join(f'0x{x:04x}' for x in a)
def generate():
    rows=[]; assets=[]; meta=[]
    for i,folder in enumerate(FOLDERS):
        d=json.loads((ROOT/'packs'/folder/'theme.json').read_text())
        c=[rgb(d['colors'][k]) for k in ROLES]
        geo='13,90,109,57,33,37,42,31,0,0' if d['dial']=='large' else '13,70,109,48,22,26,31,20,85,16'
        centre={'radar-emblem':'CP_RADAR_EMBLEM','radar':'CP_RADAR'}[d['centrepiece']]
        mask=sum(1<<SWEEPS.index(v) for v in d['sweeps'])
        rows.append('{'+json.dumps(d['name'])+','+json.dumps(d['header'])+f',{centre},{mask},{geo},'+hexes(c[:15])+',{'+hexes([c[j] for j in [0,3,5,7]])+'},'+hexes(c[15:])+'},')
        file=ROOT/'packs'/folder/'emblem.bin'; emblem='nullptr'
        if file.exists():
            b=file.read_bytes(); assert b[:4]==b'UVE\x01'
            w,h,n=b[4:7]; pix=b[8+2*n:]; assert len(pix)==w*h and n<=16
            packed=bytes((pix[j]<<4)|(pix[j+1] if j+1<len(pix) else 0) for j in range(0,len(pix),2))
            assets.append(f'static const uint8_t bundledPixels{i}[] = {{'+','.join(str(x) for x in packed)+'};')
            colors=[int.from_bytes(b[8+j*2:10+j*2],'little') for j in range(n)]
            assets.append(f'static const themepack::Emblem bundledEmblem{i} = '+'{'+f'{w},{h},{n},'+'{'+hexes(colors)+'},'+f'bundledPixels{i},true'+'};')
            emblem=f'&bundledEmblem{i}'
        meta.append('{'+f'{SWEEPS.index(d["sweep"])},{RITES.index(d["alert"])},{d.get("artOpacity",100)},{d.get("artScale",82)},'+('true' if d.get('badge')=='diamond' else 'false')+f',{emblem}'+'},')
    source=(ROOT/'ui/muffin.h').read_text()
    raw=source.split('inline constexpr uint8_t MUFFIN_PX',1)[1].split('{',1)[1].split('};',1)[0]
    nums=[int(v.strip(),0) for v in re.sub(r'//[^\n]*','',raw).split(',') if v.strip()]
    assert len(nums)==72*72 and max(nums)<16
    packed=[(nums[i]<<4)|nums[i+1] for i in range(0,len(nums),2)]
    (ROOT/'ui/muffin_packed.inc').write_text('// Lossless 4-bit indices generated from ui/muffin.h.\nstatic const uint8_t MUFFIN_PACKED[] = {'+','.join(map(str,packed))+'};\n')
    prefix='// Generated by tools/generate_bundled_themes.py; edit packs/ sources.\n'
    (ROOT/'ui/bundled_theme_rows.inc').write_text(prefix+'\n'.join(rows)+'\n')
    (ROOT/'ui/bundled_theme_assets.inc').write_text(prefix+'\n'.join(assets)+'\nstatic const BundledMeta BUNDLED_META[] = {\n'+'\n'.join(meta)+'\n};\n')
if __name__=='__main__': generate()
