#!/usr/bin/env python3
"""Turn an animated GIF into a colour radar.vid (v2) for the Waveshare engine's radar disc.

    gif2radar.py in.gif out.vid [--fps N] [--header out.h [--name COSMIC_CLIP]] [--preview sheet.png]
    gif2radar.py --selftest

Each frame is composited onto black, scaled to 102x102 and quantised to ONE shared 16-colour palette (a palette
per frame would shimmer), no dithering (dither noise changes from frame to frame). The result is the v2 file
ui/themepack.h parseClip reads: 'UVRV', 2, 102, 102, fps, frames (u16 LE), 2 reserved, 16 RGB565 LE palette
entries, then the frames at 4 bits per pixel (high nibble first). The fps comes from the GIF's frame delay unless
--fps is given. --header also writes the same bytes as a C array, which is how the COSMIC MUFFIN theme carries its
clip inside the firmware (device/cosmic_muffin_clip.h, played by device/engine_adapter.cpp). Needs Pillow.
"""
import io
import sys

SIZE = 102
FRAME_BYTES = (SIZE * SIZE + 1) // 2
PAL_ENTRIES = 16
# 16 colours cannot hold a vivid picture: plain median cut averages the pink and orange cores into pale blue-grey. A boost
# of saturation and contrast before quantising, and a k-means refinement of the palette, keeps the colour that reads on a
# 102 px disc (chosen by eye from the COSMIC MUFFIN gif; 1.0 turns each boost off).
COLOUR_BOOST = 1.5
CONTRAST_BOOST = 1.15
KMEANS = 8
MAX_FRAMES = 149            # a colour clip: (MAX_CLIP - header - palette) / frame bytes, as parseClip counts it


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def load_frames(img):
    """Every frame of the GIF as an RGB image on black, plus the delay in ms (the first frame's)."""
    from PIL import Image, ImageSequence
    frames, delay = [], None
    for f in ImageSequence.Iterator(img):
        if delay is None:
            delay = f.info.get("duration")
        rgba = f.convert("RGBA")
        canvas = Image.new("RGBA", rgba.size, (0, 0, 0, 255))
        canvas.alpha_composite(rgba)
        frames.append(canvas.convert("RGB"))
    return frames, delay


def unloop(frames):
    """A GIF that is one short cycle played over and over (frame k+p equals frame k, p dividing the count) is stored as
    the one cycle: the same animation for a fraction of the flash."""
    raw = [f.tobytes() for f in frames]
    n = len(raw)
    for p in range(1, n // 2 + 1):
        if n % p == 0 and all(raw[k] == raw[k % p] for k in range(n)):
            return frames[:p]
    return frames


def to_clip(frames, fps, colour=COLOUR_BOOST, contrast=CONTRAST_BOOST):
    """The radar.vid v2 bytes for these RGB frames, and the indexed frames (for previews and tests)."""
    from PIL import Image
    n = len(frames)
    if not 1 <= n <= MAX_FRAMES:
        raise SystemExit("a colour radar.vid is 1 to %d frames (the GIF has %d)" % (MAX_FRAMES, n))
    if not 1 <= fps <= 30:
        raise SystemExit("a radar.vid is 1 to 30 fps (got %d)" % fps)
    from PIL import ImageEnhance
    small = [f.resize((SIZE, SIZE), Image.Resampling.LANCZOS) for f in frames]
    if contrast != 1.0: small = [ImageEnhance.Contrast(f).enhance(contrast) for f in small]
    if colour != 1.0:   small = [ImageEnhance.Color(f).enhance(colour) for f in small]
    mosaic = Image.new("RGB", (SIZE, SIZE * n))
    for k, f in enumerate(small):
        mosaic.paste(f, (0, SIZE * k))
    q = mosaic.quantize(colors=PAL_ENTRIES, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE, kmeans=KMEANS)
    pal = q.getpalette()[:3 * PAL_ENTRIES]
    pal += [0] * (3 * PAL_ENTRIES - len(pal))
    idx = list(q.getdata())
    assert max(idx) < PAL_ENTRIES
    out = bytearray(b"UVRV" + bytes([2, SIZE, SIZE, fps, n & 255, n >> 8, 0, 0]))
    for e in range(PAL_ENTRIES):
        v = rgb565(pal[3 * e], pal[3 * e + 1], pal[3 * e + 2])
        out += bytes([v & 255, v >> 8])
    frames_idx = []
    for k in range(n):
        px = idx[k * SIZE * SIZE:(k + 1) * SIZE * SIZE]
        frames_idx.append(px)
        px = px + [0] * (len(px) % 2)
        out += bytes((px[i] << 4) | px[i + 1] for i in range(0, len(px), 2))
    assert len(out) == 12 + 32 + n * FRAME_BYTES
    return bytes(out), frames_idx


def c_header(data, name, src):
    lines = ["// generated by tools/gif2radar.py from %s -- do not edit." % src,
             "// A colour radar.vid (v2), %d bytes: the same file a theme pack carries, parsed with themepack::parseClip." % len(data),
             "#pragma once", "#include <stdint.h>", "",
             "static const uint8_t %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 32):
        lines.append(",".join(str(b) for b in data[i:i + 32]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def preview(clip, frames_idx, path, cols=10):
    from PIL import Image
    pal = [((clip[12 + 2 * e] | (clip[13 + 2 * e] << 8))) for e in range(PAL_ENTRIES)]
    rgb = [(((v >> 11) & 31) * 255 // 31, ((v >> 5) & 63) * 255 // 63, (v & 31) * 255 // 31) for v in pal]
    n = len(frames_idx)
    rows = (n + cols - 1) // cols
    sheet = Image.new("RGB", (cols * SIZE, rows * SIZE))
    for k, px in enumerate(frames_idx):
        im = Image.new("RGB", (SIZE, SIZE))
        im.putdata([rgb[i] for i in px])
        sheet.paste(im, ((k % cols) * SIZE, (k // cols) * SIZE))
    sheet.save(path)


def selftest():
    from PIL import Image
    colours = [(255, 0, 0), (0, 255, 0), (0, 0, 255)]          # three flat frames: one colour each, so the palette must hold all three
    imgs = [Image.new("RGB", (40, 40), c) for c in colours]
    buf = io.BytesIO()
    imgs[0].save(buf, format="GIF", save_all=True, append_images=imgs[1:], duration=100, loop=0)
    buf.seek(0)
    frames, delay = load_frames(Image.open(buf))
    ok = len(frames) == 3 and delay == 100
    fps = max(1, min(30, round(1000 / delay)))
    clip, fidx = to_clip(frames, fps)
    ok = ok and clip[:4] == b"UVRV" and clip[4] == 2 and clip[5] == SIZE and clip[6] == SIZE and clip[7] == 10
    ok = ok and clip[8] | (clip[9] << 8) == 3 and clip[10] == 0 and clip[11] == 0
    ok = ok and len(clip) == 12 + 32 + 3 * FRAME_BYTES
    pal = [clip[12 + 2 * e] | (clip[13 + 2 * e] << 8) for e in range(PAL_ENTRIES)]
    want = [rgb565(*c) for c in colours]
    for f in range(3):                                        # frame f decodes (via the palette) to its own flat colour
        ok = ok and len(set(fidx[f])) == 1 and pal[fidx[f][0]] == want[f]
    packed = clip[12 + 32:12 + 32 + FRAME_BYTES]
    ok = ok and packed[0] == ((fidx[0][0] << 4) | fidx[0][1])  # high nibble first
    ok = ok and len(unloop(frames)) == 3 and len(unloop(frames + frames)) == 3 and len(unloop(frames + frames[:2])) == 5   # a repeated cycle is stored once; a partial repeat is not
    ok = ok and len(unloop([frames[0]] * 4)) == 1
    hdr = c_header(clip, "TEST_CLIP", "selftest")
    ok = ok and "TEST_CLIP[%d]" % len(clip) in hdr and hdr.count(",") >= len(clip)
    print("gif2radar selftest: " + ("all passed" if ok else "FAILED"))
    return 0 if ok else 1


def main(argv):
    if "--selftest" in argv:
        return selftest()
    import argparse
    from PIL import Image
    ap = argparse.ArgumentParser()
    ap.add_argument("src"); ap.add_argument("out")
    ap.add_argument("--fps", type=int, default=0)
    ap.add_argument("--header"); ap.add_argument("--name", default="COSMIC_CLIP")
    ap.add_argument("--colour", type=float, default=COLOUR_BOOST, help="saturation boost before quantising (1.0 = off)")
    ap.add_argument("--contrast", type=float, default=CONTRAST_BOOST, help="contrast boost before quantising (1.0 = off)")
    ap.add_argument("--still", nargs=2, metavar=("FRAME", "OUT.png"), help="also write one frame, colour-boosted, full size (the source for tools/gen_muffin.py)")
    ap.add_argument("--preview")
    a = ap.parse_args(argv)
    frames, delay = load_frames(Image.open(a.src))
    if a.still:
        from PIL import ImageEnhance
        f = frames[int(a.still[0])]
        f = ImageEnhance.Color(ImageEnhance.Contrast(f).enhance(a.contrast)).enhance(a.colour)
        f.save(a.still[1]); print("%s: frame %s, colour-boosted" % (a.still[1], a.still[0]))
    total = len(frames); frames = unloop(frames)
    if len(frames) != total: print("%d frames are a cycle of %d played %d times: stored once" % (total, len(frames), total // len(frames)))
    fps = a.fps or max(1, min(30, round(1000 / (delay or 80))))
    clip, fidx = to_clip(frames, fps, a.colour, a.contrast)
    open(a.out, "wb").write(clip)
    print("%s: %d frames at %d fps, %d bytes" % (a.out, len(frames), fps, len(clip)))
    if a.header:
        open(a.header, "w").write(c_header(clip, a.name, a.src.split("/")[-1]))
        print("%s: C array %s" % (a.header, a.name))
    if a.preview:
        preview(clip, fidx, a.preview)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
