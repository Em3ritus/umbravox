#!/usr/bin/env python3
"""Turn a video into the looping radar clip the Waveshare engine can play (ui/scan_render.h RadarVideo).

    video2radar.py --ffmpeg PATH in.mov out.vid [--fps 12] [--crop W:H:X:Y]
                   [--black 24] [--white 235] [--max-seconds 12] [--preview sheet.png]
    video2radar.py --ffmpeg PATH in.mov out.h ...        the same clip as a C header (see below)

Crops a square from the video (default: the whole width, centred), scales it to 102x102, keeps --fps frames a
second in 16 grey levels, and writes either
  out.vid   the radar.vid a theme pack carries (ui/themepack.h parseClip; drop it in the pack folder beside
            theme.json), or
  out.h     a C header (RV_W, RV_H, RV_FRAMES, RV_FPS, RV_DATA) that device/engine_adapter.cpp plays on the built-in
            seal theme when it is saved as device/radarvid_data.h (gitignored). A pack's radar.vid wins over it.
The player draws it 2x inside the radar disc, so 102 fills the 205 px disc. Audio is dropped. Needs ffmpeg (any
build) and Python with numpy and pillow (the preview sheet needs pillow only).
"""
import argparse, subprocess, sys

ap = argparse.ArgumentParser()
ap.add_argument("src"); ap.add_argument("out")
ap.add_argument("--ffmpeg", default="ffmpeg")
ap.add_argument("--fps", type=int, default=12)
ap.add_argument("--crop", default=None, help="W:H:X:Y of the square to keep (default: full width, centred)")
ap.add_argument("--black", type=int, default=24, help="source grey level that becomes 0")
ap.add_argument("--white", type=int, default=235, help="source grey level that becomes 15")
ap.add_argument("--max-seconds", type=float, default=12.0)
ap.add_argument("--preview", default=None)

SIZE = 102
FRAME_BYTES = (SIZE * SIZE + 1) // 2


def vid_bytes(packed, frames, fps):
    """radar.vid: 'UVRV', version 1, 102, 102, fps, frames (u16 LE), 2 reserved, then the frames. As ui/themepack.h
    parseClip reads it and web/designer/js/radarvideo.js clipFile writes it."""
    if not 1 <= frames <= 150 or not 1 <= fps <= 30:
        raise SystemExit("a radar.vid is 1 to 150 frames at 1 to 30 fps (got %d frames, %d fps)" % (frames, fps))
    return b"UVRV" + bytes([1, SIZE, SIZE, fps, frames & 255, frames >> 8, 0, 0]) + bytes(packed)


def test_levels(frames):
    """The deterministic levels the Node test feeds the designer's encoder (test/video2radar.test.mjs)."""
    return [[(i * 7 + f * 3 + (i >> 5)) % 16 for i in range(SIZE * SIZE)] for f in range(frames)]


def pack_levels(frames_levels):
    """Two levels per byte, high nibble first, frame after frame (the pure-Python twin of the numpy path below)."""
    out = bytearray()
    for lv in frames_levels:
        lv = list(lv) + [0] * (len(lv) % 2)
        out += bytes((lv[i] << 4) | lv[i + 1] for i in range(0, len(lv), 2))
    return bytes(out)


if "--selftest" in sys.argv:
    v = vid_bytes(pack_levels(test_levels(2)), 2, 12)
    first = test_levels(1)[0]
    ok = (v[:12] == b"UVRV" + bytes([1, SIZE, SIZE, 12, 2, 0, 0, 0]) and len(v) == 12 + 2 * FRAME_BYTES
          and v[12] == ((first[0] << 4) | first[1]))
    print("video2radar selftest: " + ("all passed" if ok else "FAILED"))
    sys.exit(0 if ok else 1)
if "--emit-test-vid" in sys.argv:
    k = sys.argv.index("--emit-test-vid")
    n, fps = int(sys.argv[k + 1]), int(sys.argv[k + 2])
    sys.stdout.buffer.write(vid_bytes(pack_levels(test_levels(n)), n, fps))
    sys.exit(0)

import numpy as np
a = ap.parse_args()
a.size = SIZE

vf = []
if a.crop: vf.append("crop=%s" % a.crop)
else: vf.append("crop=min(iw\\,ih):min(iw\\,ih)")
vf += ["scale=%d:%d:flags=area" % (a.size, a.size), "fps=%d" % a.fps, "format=gray"]
cmd = [a.ffmpeg, "-v", "error", "-t", str(a.max_seconds), "-i", a.src, "-vf", ",".join(vf), "-f", "rawvideo", "-"]
raw = subprocess.run(cmd, check=True, stdout=subprocess.PIPE).stdout
n = len(raw) // (a.size * a.size)
if n < 2: sys.exit("no frames decoded")
g = np.frombuffer(raw[:n * a.size * a.size], dtype=np.uint8).reshape(n, a.size * a.size).astype(np.float32)
q = np.clip((g - a.black) / float(a.white - a.black), 0, 1)
lv = np.rint(q * 15).astype(np.uint8)
if lv.shape[1] % 2: lv = np.concatenate([lv, np.zeros((n, 1), np.uint8)], axis=1)
packed = (lv[:, 0::2] << 4) | lv[:, 1::2]
data = packed.reshape(-1)
if a.out.endswith(".vid"):
    with open(a.out, "wb") as f:
        f.write(vid_bytes(bytes(data), n, a.fps))
else:
  with open(a.out, "w") as f:
    f.write("// generated by tools/video2radar.py -- do not edit. %d frames of %dx%d at %d fps, %d bytes.\n" % (n, a.size, a.size, a.fps, len(data)))
    f.write("#pragma once\n#include <stdint.h>\n")
    f.write("#define RV_W %d\n#define RV_H %d\n#define RV_FRAMES %d\n#define RV_FPS %d\n" % (a.size, a.size, n, a.fps))
    f.write("static const uint8_t RV_DATA[%d] = {\n" % len(data))
    for i in range(0, len(data), 24):
        f.write(",".join(str(int(b)) for b in data[i:i + 24]) + ",\n")
    f.write("};\n")
print("%d frames, %d bytes -> %s" % (n, len(data) + (12 if a.out.endswith(".vid") else 0), a.out))
if a.preview:
    from PIL import Image
    idx = np.linspace(0, n - 1, 8).astype(int)
    tiles = [(q[i].reshape(a.size, a.size) * 15).round() / 15 * 255 for i in idx]
    sheet = np.concatenate(tiles, axis=1).astype(np.uint8)
    Image.fromarray(sheet).resize((sheet.shape[1] * 2, sheet.shape[0] * 2), Image.NEAREST).save(a.preview)
