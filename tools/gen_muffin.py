#!/usr/bin/env python3
"""Generate ui/muffin.h -- the COSMIC MUFFIN dial centrepiece.

Unlike the Baphomet sigil (a textured line drawing baked to a 4-level ramp),
the muffin is a full-colour pixel-art image, so it ships as an indexed bitmap
plus an RGB565 colour table. The source is already stylised and chunky, so the
pipeline is just: crop to the muffin, area-average down (BOX, never Lanczos --
Lanczos rings on the hard pixel edges), quantise to a small palette, pack.

The bitmap is a square; drawMuffin() masks it to the dial circle at draw time.

Usage:  python3 -I tools/gen_muffin.py      # writes ui/muffin.h
        Needs Python 3 with Pillow.
"""
import hashlib
import io
import os
import sys

import PIL
from PIL import Image

SRC = "ui/art/cosmic-muffin-src.png"     # committed, so anyone can regenerate
OUT = "ui/muffin.h"
SIZE = 72                                 # square bitmap; drawMuffin scales it
NCOL = 16                                 # palette entries
CROP = (0.13, 0.07, 0.88, 0.86)           # muffin bbox as fractions of the art


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def main():
    if not os.path.exists(SRC):
        sys.exit("gen_muffin: cannot find %s -- run from the repo root "
                 "(the source art is committed under ui/art/)" % SRC)
    try:
        with open(SRC, "rb") as fh:
            raw = fh.read()
        digest = hashlib.sha256(raw).hexdigest()
        src = Image.open(io.BytesIO(raw)).convert("RGB")
    except Exception as e:
        sys.exit("gen_muffin: cannot read %s as an image (%s)" % (SRC, e))

    w, h = src.size
    box = (int(w * CROP[0]), int(h * CROP[1]), int(w * CROP[2]), int(h * CROP[3]))
    small = src.crop(box).resize((SIZE, SIZE), Image.BOX)
    q = small.quantize(colors=NCOL, method=Image.MEDIANCUT, dither=Image.NONE)

    pal = q.getpalette()                  # flat [r,g,b, ...]
    idx = list(q.getdata())
    used = sorted(set(idx))               # compact to the colours actually used
    remap = {old: new for new, old in enumerate(used)}
    px = [remap[i] for i in idx]
    colors = [rgb565(pal[3 * i], pal[3 * i + 1], pal[3 * i + 2]) for i in used]

    f = io.StringIO()
    f.write("// GENERATED by tools/gen_muffin.py -- do not hand-edit.\n")
    f.write("//\n")
    f.write("// Regenerate with (from the repo root):  python3 -I tools/gen_muffin.py\n")
    f.write("//   Needs Python 3 with Pillow.\n")
    f.write("//   Source: %s (SHA-256 %s)\n" % (SRC, digest))
    f.write("//   Built with Pillow %s\n" % PIL.__version__)
    f.write("//\n")
    f.write("// Full-colour indexed bitmap: MUFFIN_PX holds one palette index per\n")
    f.write("// pixel; MUFFIN_PAL is the RGB565 table. drawMuffin() masks it to the\n")
    f.write("// dial circle at draw time, so the square corners never show.\n")
    f.write("#pragma once\n#include <stdint.h>\n\nnamespace ui {\n\n")
    f.write("constexpr int MUFFIN_W = %d;\nconstexpr int MUFFIN_H = %d;\n" % (SIZE, SIZE))
    f.write("constexpr int MUFFIN_NCOL = %d;\n\n" % len(colors))
    f.write("inline constexpr uint16_t MUFFIN_PAL[MUFFIN_NCOL] = {\n    ")
    f.write(" ".join("0x%04X," % c for c in colors))
    f.write("\n};\n\n")
    f.write("inline constexpr uint8_t MUFFIN_PX[MUFFIN_W * MUFFIN_H] = {\n")
    for i in range(0, len(px), 24):
        f.write("    " + "".join("%2d," % p for p in px[i:i + 24]) + "\n")
    f.write("};\n\n} // namespace ui\n")

    tmp = OUT + ".tmp"
    try:
        with open(tmp, "w") as out:
            out.write(f.getvalue())
        os.replace(tmp, OUT)
    except BaseException:
        if os.path.exists(tmp):
            os.remove(tmp)
        raise
    print("wrote %s: %dx%d, %d colours" % (OUT, SIZE, SIZE, len(colors)))


if __name__ == "__main__":
    main()
